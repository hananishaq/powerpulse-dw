-- Demand fact
CREATE TABLE IF NOT EXISTS project_dw.fact_hourly_demand (
    demand_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    authority_key BIGINT NOT NULL,
    date_key BIGINT NOT NULL,
    hour_key BIGINT NOT NULL,

    utc_hour_end TIMESTAMPTZ NOT NULL,
    local_hour_end TIMESTAMP NOT NULL,
    utc_offset_minutes SMALLINT NOT NULL,

    actual_demand_mw NUMERIC(18,4),
    forecast_demand_mw NUMERIC(18,4),
    total_generation_mw NUMERIC(18,4),

    source_snapshot_key BIGINT NOT NULL,
    source_row_number INTEGER NOT NULL,

    CONSTRAINT fk_demand_authority
        FOREIGN KEY (authority_key)
        REFERENCES project_dw.dim_balancing_authority(authority_key),

    CONSTRAINT fk_demand_date
        FOREIGN KEY (date_key)
        REFERENCES project_dw.dim_date(date_key),

    CONSTRAINT fk_demand_hour
        FOREIGN KEY (hour_key)
        REFERENCES project_dw.dim_hour(hour_key),

    CONSTRAINT fk_demand_source_snapshot
        FOREIGN KEY (source_snapshot_key)
        REFERENCES project_dw.dim_source_snapshot(source_snapshot_key),

    CONSTRAINT uq_fact_hourly_demand_grain
        UNIQUE (authority_key, utc_hour_end)
);

-- Generation fact
CREATE TABLE IF NOT EXISTS project_dw.fact_hourly_generation (
    generation_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    authority_key BIGINT NOT NULL,
    date_key BIGINT NOT NULL,
    hour_key BIGINT NOT NULL,
    energy_source_key BIGINT NOT NULL,

    utc_hour_end TIMESTAMPTZ NOT NULL,
    local_hour_end TIMESTAMP NOT NULL,
    utc_offset_minutes SMALLINT NOT NULL,

    generation_mw NUMERIC(18,4) NOT NULL,

    source_snapshot_key BIGINT NOT NULL,
    source_row_number INTEGER NOT NULL,

    CONSTRAINT fk_generation_authority
        FOREIGN KEY (authority_key)
        REFERENCES project_dw.dim_balancing_authority(authority_key),

    CONSTRAINT fk_generation_date
        FOREIGN KEY (date_key)
        REFERENCES project_dw.dim_date(date_key),

    CONSTRAINT fk_generation_hour
        FOREIGN KEY (hour_key)
        REFERENCES project_dw.dim_hour(hour_key),

    CONSTRAINT fk_generation_energy_source
        FOREIGN KEY (energy_source_key)
        REFERENCES project_dw.dim_energy_source(energy_source_key),

    CONSTRAINT fk_generation_source_snapshot
        FOREIGN KEY (source_snapshot_key)
        REFERENCES project_dw.dim_source_snapshot(source_snapshot_key),

    CONSTRAINT uq_fact_hourly_generation_grain
        UNIQUE (authority_key, utc_hour_end, energy_source_key)
);

-- Fact indexes
CREATE INDEX IF NOT EXISTS idx_fact_hourly_demand_date_key
    ON project_dw.fact_hourly_demand(date_key);

CREATE INDEX IF NOT EXISTS idx_fact_hourly_demand_hour_key
    ON project_dw.fact_hourly_demand(hour_key);

CREATE INDEX IF NOT EXISTS idx_fact_hourly_demand_source_snapshot_key
    ON project_dw.fact_hourly_demand(source_snapshot_key);

CREATE INDEX IF NOT EXISTS idx_fact_hourly_generation_date_key
    ON project_dw.fact_hourly_generation(date_key);

CREATE INDEX IF NOT EXISTS idx_fact_hourly_generation_hour_key
    ON project_dw.fact_hourly_generation(hour_key);

CREATE INDEX IF NOT EXISTS idx_fact_hourly_generation_energy_source_key
    ON project_dw.fact_hourly_generation(energy_source_key);

CREATE INDEX IF NOT EXISTS idx_fact_hourly_generation_source_snapshot_key
    ON project_dw.fact_hourly_generation(source_snapshot_key);