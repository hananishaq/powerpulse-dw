-- Create warehouse schema
CREATE SCHEMA IF NOT EXISTS project_dw;

-- Date dimension
CREATE TABLE IF NOT EXISTS project_dw.dim_date (
    date_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_date DATE NOT NULL,
    calendar_year SMALLINT NOT NULL,
    quarter_number SMALLINT NOT NULL,
    month_number SMALLINT NOT NULL,
    iso_week_year SMALLINT NOT NULL,
    iso_week_number SMALLINT NOT NULL,
    weekday_number SMALLINT NOT NULL,
    season TEXT NOT NULL,

    CONSTRAINT uq_dim_date_calendar_date
        UNIQUE (calendar_date)
);

-- Hour dimension
CREATE TABLE IF NOT EXISTS project_dw.dim_hour (
    hour_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hour_ending SMALLINT NOT NULL,
    hour_label TEXT NOT NULL,

    CONSTRAINT uq_dim_hour_hour_ending
        UNIQUE (hour_ending)
);

-- Balancing authority dimension
CREATE TABLE IF NOT EXISTS project_dw.dim_balancing_authority (
    authority_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    authority_code TEXT NOT NULL,
    authority_name TEXT NOT NULL,
    region_code TEXT NOT NULL,
    region_name TEXT NOT NULL,

    CONSTRAINT uq_dim_balancing_authority_code
        UNIQUE (authority_code)
);

-- Energy source dimension
CREATE TABLE IF NOT EXISTS project_dw.dim_energy_source (
    energy_source_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_column TEXT NOT NULL,
    source_label TEXT NOT NULL,
    source_group TEXT NOT NULL,

    CONSTRAINT uq_dim_energy_source_column
        UNIQUE (source_column)
);

-- Source snapshot dimension
CREATE TABLE IF NOT EXISTS project_dw.dim_source_snapshot (
    source_snapshot_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name TEXT NOT NULL,
    source_url TEXT NOT NULL,
    sha256 CHAR(64) NOT NULL,
    retrieved_at_utc TIMESTAMPTZ NOT NULL,
    source_row_count INTEGER NOT NULL,

    CONSTRAINT uq_dim_source_snapshot_file_hash
        UNIQUE (file_name, sha256)
);
