-- 4 rows, from data_acquisition/data/source_manifest.json
CREATE TABLE IF NOT EXISTS project_staging.stg_source_file (
    file_name          text         NOT NULL,   -- official file name (URL basename)
    source_url         text         NOT NULL,
    retrieved_at_utc   timestamptz  NOT NULL,
    sha256             char(64)     NOT NULL,   -- SHA-256 of the complete downloaded file
    source_row_count   integer      NOT NULL,   -- data records in the complete source CSV
    selected_row_count integer      NOT NULL,   -- extra: rows in the delivered 5-authority subset
    subset_file_name   text         NOT NULL,   -- extra: delivered CSV that was loaded
    subset_sha256      char(64)     NOT NULL,   -- extra: SHA-256 of the delivered subset CSV
    CONSTRAINT pk_stg_source_file PRIMARY KEY (file_name, sha256)
);

-- 5 rows, from authority_reference.csv
CREATE TABLE IF NOT EXISTS project_staging.stg_authority_reference (
    authority_code     text  PRIMARY KEY,
    authority_name     text  NOT NULL,
    reporting_time_zone text NOT NULL,
    region_code        text  NOT NULL,
    region_name        text  NOT NULL
);

-- 19 rows, from energy_source_mapping.csv. source_column keeps the ORIGINAL header spelling.
CREATE TABLE IF NOT EXISTS project_staging.stg_energy_source_mapping (
    source_column            text    PRIMARY KEY,   -- exact CSV header, e.g. 'Net Generation (MW) from Coal'
    source_label             text    NOT NULL,
    source_group             text    NOT NULL,
    numeric_cells_in_baseline integer NOT NULL,
    clean_column             text    NOT NULL       -- extra: matching gen_* column in stg_eia930_balance_clean
);

-- ---------------------------------------------------------------------
-- Raw landing table: every data column is TEXT, exactly as read from the CSV.
-- Only the REPORTED columns are kept (Imputed / Adjusted variants are not loaded).
-- A fuel column that does not exist in a file is NULL for that file's rows;
-- a blank cell that exists is an empty string ''.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS project_staging.stg_eia930_balance_raw (
    raw_row_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_file         text,      -- _SourceFile
    source_row          text,      -- _SourceRow (data-record number in the full EIA file, header excluded)
    subset_row_number   integer,   -- extra: 1-based data row inside the delivered subset CSV
    balancing_authority text,      -- Balancing Authority
    region              text,      -- Region
    data_date           text,      -- Data Date
    hour_number         text,      -- Hour Number
    local_time_end      text,      -- Local Time at End of Hour
    utc_time_end        text,      -- UTC Time at End of Hour
    demand_forecast_mw  text,      -- Demand Forecast (MW)
    demand_mw           text,      -- Demand (MW)
    net_generation_mw   text,      -- Net Generation (MW)
    gen_coal                                    text,
    gen_natural_gas                             text,
    gen_nuclear                                 text,
    gen_all_petroleum_products                  text,
    gen_hydropower_and_pumped_storage           text,
    gen_solar                                   text,
    gen_wind                                    text,
    gen_other_fuel_sources                      text,
    gen_unknown_fuel_sources                    text,
    gen_hydropower_excluding_pumped_storage     text,
    gen_pumped_storage                          text,
    gen_solar_without_integrated_battery_storage text,
    gen_solar_with_integrated_battery_storage   text,
    gen_wind_without_integrated_battery_storage text,
    gen_wind_with_integrated_battery_storage    text,
    gen_battery_storage                         text,
    gen_other_energy_storage                    text,
    gen_unknown_energy_storage                  text,
    gen_geothermal                              text,
    loaded_at           timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Clean typed table: the ONLY staging table Steps 3-5 read facts from.
-- Missing measures are NULL (never 0). Negative net generation is kept.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS project_staging.stg_eia930_balance_clean (
    authority_code      text         NOT NULL,
    region_code         text         NOT NULL,                 -- extra
    data_date           date         NOT NULL,                 -- publisher operating day
    hour_number         smallint     NOT NULL,                 -- 1..25 (25 = repeated hour on the autumn clock-change day)
    local_hour_end      timestamp    NOT NULL,                 -- source wall-clock label, no time zone
    utc_hour_end        timestamptz  NOT NULL,                 -- unambiguous instant (UTC)
    utc_offset_minutes  smallint     NOT NULL,                 -- local minus UTC, in minutes
    forecast_demand_mw  numeric(18,4),
    actual_demand_mw    numeric(18,4),
    total_generation_mw numeric(18,4),
    gen_coal                                    numeric(18,4),
    gen_natural_gas                             numeric(18,4),
    gen_nuclear                                 numeric(18,4),
    gen_all_petroleum_products                  numeric(18,4),
    gen_hydropower_and_pumped_storage           numeric(18,4),
    gen_solar                                   numeric(18,4),
    gen_wind                                    numeric(18,4),
    gen_other_fuel_sources                      numeric(18,4),
    gen_unknown_fuel_sources                    numeric(18,4),
    gen_hydropower_excluding_pumped_storage     numeric(18,4),
    gen_pumped_storage                          numeric(18,4),
    gen_solar_without_integrated_battery_storage numeric(18,4),
    gen_solar_with_integrated_battery_storage   numeric(18,4),
    gen_wind_without_integrated_battery_storage numeric(18,4),
    gen_wind_with_integrated_battery_storage    numeric(18,4),
    gen_battery_storage                         numeric(18,4),
    gen_other_energy_storage                    numeric(18,4),
    gen_unknown_energy_storage                  numeric(18,4),
    gen_geothermal                              numeric(18,4),
    source_file         text         NOT NULL,                 -- official file name = stg_source_file.file_name
    source_sha256       char(64)     NOT NULL,                 -- extra: snapshot hash, lets Step 4 find the snapshot key
    source_row          integer      NOT NULL,
    cleaned_at          timestamptz  NOT NULL DEFAULT now(),   -- extra
    CONSTRAINT pk_stg_eia930_balance_clean PRIMARY KEY (authority_code, utc_hour_end),
    CONSTRAINT uq_stg_clean_source_row     UNIQUE (source_file, source_row),
    CONSTRAINT ck_stg_clean_hour_number    CHECK (hour_number BETWEEN 1 AND 25),
    CONSTRAINT ck_stg_clean_utc_offset     CHECK (utc_offset_minutes IN (-480, -420, -360, -300, -240))
);

-- ---------------------------------------------------------------------
-- Rejected rows and nulled values (one row per problem)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS project_staging.stg_load_exception (
    exception_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_row_id    bigint,
    rule_id       text        NOT NULL,
    reason        text        NOT NULL,
    action_taken  text        NOT NULL,   -- 'ROW_REJECTED' or 'VALUE_SET_NULL'
    column_name   text,
    bad_value     text,
    source_file   text,
    source_row    text,
    logged_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_stg_exception_action CHECK (action_taken IN ('ROW_REJECTED', 'VALUE_SET_NULL'))
);

-- ---------------------------------------------------------------------
-- Before/after counts for every cleaning rule (raw material of the report)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS project_staging.stg_cleaning_log (
    log_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id        text        NOT NULL,
    rule_name      text        NOT NULL,
    scope          text        NOT NULL,   -- 'ALL', a file name, a column name ...
    rows_before    bigint,
    rows_after     bigint,
    rows_affected  bigint,
    detail         text,
    logged_at      timestamptz NOT NULL DEFAULT now()
);
