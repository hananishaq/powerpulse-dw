-- ---------------------------------------------------------------------
-- Safe parsing helpers: return NULL instead of raising an error, so one
-- bad cell is logged as an exception instead of aborting the whole load.
-- ---------------------------------------------------------------------

-- Plain decimal only (no NaN, Infinity, thousands separators or text).
CREATE OR REPLACE FUNCTION project_staging.try_numeric(p text)
RETURNS numeric LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    IF p IS NULL OR BTRIM(p) = '' THEN
        RETURN NULL;
    END IF;
    IF BTRIM(p) !~ '^[+-]?[0-9]+(\.[0-9]+)?$' THEN
        RETURN NULL;
    END IF;
    RETURN BTRIM(p)::numeric;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END $$;

-- 'MM/DD/YYYY' -> date
CREATE OR REPLACE FUNCTION project_staging.try_date_mdy(p text)
RETURNS date LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE m text[];
BEGIN
    m := regexp_match(BTRIM(p), '^(\d{1,2})/(\d{1,2})/(\d{4})$');
    IF m IS NULL THEN
        RETURN NULL;
    END IF;
    RETURN make_date(m[3]::int, m[1]::int, m[2]::int);
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END $$;

-- 'MM/DD/YYYY h:mm:ss AM' -> timestamp WITHOUT time zone (wall-clock label).
-- Built with make_timestamp, so the session time zone can never shift it.
CREATE OR REPLACE FUNCTION project_staging.try_timestamp_mdy12(p text)
RETURNS timestamp LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE m text[]; h int;
BEGIN
    m := regexp_match(UPPER(BTRIM(p)),
         '^(\d{1,2})/(\d{1,2})/(\d{4}) (\d{1,2}):(\d{2}):(\d{2}) (AM|PM)$');
    IF m IS NULL THEN
        RETURN NULL;
    END IF;
    h := m[4]::int;
    IF h < 1 OR h > 12 THEN
        RETURN NULL;
    END IF;
    h := (h % 12) + CASE WHEN m[7] = 'PM' THEN 12 ELSE 0 END;
    RETURN make_timestamp(m[3]::int, m[1]::int, m[2]::int, h, m[5]::int, m[6]::int);
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END $$;

