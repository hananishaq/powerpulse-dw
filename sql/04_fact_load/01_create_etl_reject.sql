CREATE TABLE IF NOT EXISTS project_dw.etl_reject (
    reject_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id UUID NOT NULL,
    step_name TEXT NOT NULL,
    rejected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source_file TEXT,
    source_row_number INTEGER,
    authority_code TEXT,
    data_date DATE,
    utc_hour_end TIMESTAMPTZ,
    energy_source_column TEXT,
    rejection_reason TEXT NOT NULL,
    source_record JSONB
);

CREATE INDEX IF NOT EXISTS idx_etl_reject_run_id
    ON project_dw.etl_reject(run_id);

CREATE INDEX IF NOT EXISTS idx_etl_reject_step_name
    ON project_dw.etl_reject(step_name);